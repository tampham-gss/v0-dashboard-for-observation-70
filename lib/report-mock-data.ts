/** Dòng phụ đề hiển thị phạm vi kỳ / chi nhánh đang áp dụng (đã lọc). */
export function appliedFiltersCaption(filters: ReportFilters): string {
  const period =
    filters.periodType === 'week'
      ? `${filters.week} · ${filters.year}`
      : `Tháng ${filters.month} · ${filters.year}`
  const branch = filters.branch === 'all' ? 'Toàn khu vực' : `Khu vực ${filters.branch}`
  const extras: string[] = []
  if (filters.warehouse !== 'all') extras.push(filters.warehouse)
  if (filters.route !== 'all') extras.push(filters.route)
  if (filters.staff !== 'all') extras.push(filters.staff)
  if (filters.opsCs !== 'all') extras.push(`OPS ${filters.opsCs}`)
  const extra = extras.length ? ` · ${extras.join(' · ')}` : ''
  return `${period} · ${branch}${extra}`
}

